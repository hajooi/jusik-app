export type ModuleType = 'guide_steps' | 'resources' | 'cta';

export interface GuideStep {
  stepNumber: number;
  title: string;
  description?: string;
  bullets?: string[];
  icon?: string;
}

export interface GuideStepsModule {
  type: 'guide_steps';
  title: string;
  description?: string;
  steps: GuideStep[];
}

export interface ResourceLink {
  label: string;
  url: string;
  type?: 'link' | 'file' | 'reference';
  description?: string;
}

export interface ResourcesModule {
  type: 'resources';
  title: string;
  description?: string;
  links: ResourceLink[];
}

export interface CTAModule {
  type: 'cta';
  title: string;
  description: string;
  buttonText: string;
  buttonUrl: string;
  badge?: string;
  isExternal?: boolean;
  benefits?: string[];
}

export interface BookSection {
  title: string;
  image?: {
    src: string;
    alt: string;
    caption?: string;
  };
  paragraphs: string[];
  callout?: string;
  interactiveTool?: 'labor_simulator' | 'wealth_chart' | 'class_detector' | 'cisco_mania';
}

